def test_big_dump_and_memdiff(fake_cli, capsys, tmp_path):
    fake_cli.mem.extend(bytes(0x1000 - len(fake_cli.mem)))
    fake_cli.mem[0x300:0x304] = b"\x11\x22\x33\x44"   # pretend a macro landed here
    cli.main(["dump", "--end", "0x1000", "--save", str(tmp_path / "a.json")])
    out = capsys.readouterr().out
    assert "0x300: 11 22 33 44" in out and "0x20-0x2ff: all 00" in out and "0x308-0xfff: all 00" in out
    fake_cli.mem[0x302] = 0x99
    fake_cli.mem[0x0D] = 0xAA
