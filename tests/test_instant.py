def test_linux_single_hidraw_node_for_interface_1():
    """On Linux, interface 1 is ONE hidraw node whose descriptor holds all its collections
    (consumer, vendor 0xFF00 events, vendor 0xFF01 control, system, keyboard)."""
    consumer = bytes.fromhex("05 0c 09 01 a1 01 85 02 75 10 95 01 09 01 81 00 c0")
    combined = consumer + EVENT_DESC + CONTROL_DESC
    mouse_if0 = HidrawNode("hidraw3", "/dev/hidraw3", 3, 0x30FA, 0x1440, "INSTANT USB Gaming Mouse", 0,
                           bytes.fromhex("05 01 09 02 a1 01 85 01 09 01 a1 00 05 09 19 01 29 05 15 00 25 01 "
                                         "95 05 75 01 81 02 95 01 75 03 81 01 c0 c0"))
    mouse_if1 = HidrawNode("hidraw4", "/dev/hidraw4", 3, 0x30FA, 0x1440, "INSTANT USB Gaming Mouse", 1, combined)
    node = ins.find_control_node([mouse_if0, mouse_if1])
    assert node is mouse_if1
    assert node.summary.wire_length("feature", 0x07) == 8


def test_set_active_level_changes_only_low_bits():
    fake = FakeInstantMouse()
    fake.mem[0x18:0x20] = bytes.fromhex("19 3f 32 00 9a ff 00 00")  # real dump: level 2 active
    m = ins.InstantMouse(fake, sleep=no_sleep)
    res = m.set_active_level(4, pid=0x1440)  # level 5
    assert res["changed"] and fake.mem[0x18] == 0x1C and bytes(fake.mem[0x19:0x20]) == bytes.fromhex("3f 32 00 9a ff 00 00")
    assert fake.reloads == 1 and {p[4] for p in fake.writes()} == {0x18}
    # already active: nothing written, but the mouse still reloads so it really switches
    fake.sent.clear()
    assert m.set_active_level(4)["changed"] is False and fake.writes() == [] and fake.reloads == 2


