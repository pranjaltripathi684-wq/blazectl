def test_dump_and_header_check():
    fake = FakeInstantMouse()
    m = ins.InstantMouse(fake, sleep=no_sleep)
    mem = m.dump()
    assert b"".join(mem.values()) == bytes(fake.mem)
    assert fake.writes() == []  # dump is read-only
    ok, msg = m.check_header(mem[0], pid=0x1440)
    assert ok and "PID found" in msg
    assert m.get_dpi()["codes"] == FACTORY_DPI


def test_set_dpi_writes_verifies_and_reloads():
    fake = FakeInstantMouse()
    m = ins.InstantMouse(fake, sleep=no_sleep)
    res = m.set_dpi([4, 8, 12, 16, 20, 24], pid=0x1440)
    assert res["changed"] and res["codes"] == [4, 8, 12, 16, 20, 24]
    assert ins.decode_dpi(bytes(fake.mem[0x10:0x18])) == [4, 8, 12, 16, 20, 24]
    assert fake.mem[0x08:0x10] == bytes([1, 2, 3, 4, 5, 6, 0, 0])  # buttons untouched
    assert fake.reloads == 1
    assert {p[4] for p in fake.writes()} == {0x10}  # only the DPI block was written


def test_set_dpi_noop_when_unchanged():
    fake = FakeInstantMouse()
    assert ins.InstantMouse(fake, sleep=no_sleep).set_dpi(FACTORY_DPI)["changed"] is False
    assert fake.writes() == []


def test_failed_write_is_detected_and_restored():
    fake = FakeInstantMouse(failed_commits=1)
    before = bytes(fake.mem)
    with pytest.raises(ins.InstantError, match="did not store.*restored"):
        ins.InstantMouse(fake, sleep=no_sleep).set_dpi([4, 8, 12, 16, 20, 24])
    assert bytes(fake.mem) == before
    assert fake.reloads == 0


def test_dpi_write_locked_when_header_differs():
    mem = default_memory()
    mem[0:3] = b"\x00\x00\x00"
    fake = FakeInstantMouse(mem)
    with pytest.raises(ins.InstantError, match="locked"):
        ins.InstantMouse(fake, sleep=no_sleep).set_dpi([4, 8, 12, 16, 20, 24])
    assert fake.writes() == []


def test_dpi_write_locked_when_block_implausible():
    mem = default_memory()
    mem[0x10:0x18] = bytes.fromhex("00 00 00 00 00 b0 00 00")  # decodes to an invalid code 11
    fake = FakeInstantMouse(mem)
    with pytest.raises(ins.InstantError, match="not a valid set"):
        ins.InstantMouse(fake, sleep=no_sleep).set_dpi([4, 8, 12, 16, 20, 24])
    assert fake.writes() == []


def test_only_known_blocks_are_writable():
    m = ins.InstantMouse(FakeInstantMouse(), sleep=no_sleep)
    for addr in (ins.HEADER_BLOCK, 0x20, 0x40, 0x80):
        with pytest.raises(ins.InstantError, match="refusing"):
            m.write_block(addr, bytes(8))


def test_find_control_node_picks_ff01_collection():
    def node(name, desc, page):
        n = HidrawNode(name, name, 0, 0x30FA, 0x1440, "INSTANT USB Gaming Mouse", 1, desc)
        return n
    nodes = [node("hid5", EVENT_DESC, 0xFF00), node("hid6", CONTROL_DESC, 0xFF01)]
    assert ins.find_control_node(nodes).name == "hid6"
    assert ins.find_control_node(nodes, pid=0x1040) is None


