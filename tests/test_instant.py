"""Instant (30fa:xxxx) driver tests.

isy_vectors.json was generated by running julianfdz/open-isy4500-customizer's
own lib/protocol.mjs (MIT), which is verified on real 30fa:1040 hardware, so
these tests pin our encoder to a known-working implementation byte for byte.
"""

import json
import os

import pytest

from blazectl import cli
from blazectl.drivers import instant as ins
from blazectl.hidraw import HidrawNode

VECTORS = json.load(open(os.path.join(os.path.dirname(__file__), "isy_vectors.json")))
ISY_MODE_IDS = {"static", "breathing", "breathing-multi", "rainbow", "spectrum", "fill", "loop",
                "enraptured", "flicker", "ripple", "startrek", "off"}

CONTROL_DESC = bytes.fromhex("06 01 ff 09 01 a1 01 85 07 75 08 95 07 09 01 b1 02 c0")
EVENT_DESC = bytes.fromhex("06 00 ff 09 01 a1 01 85 06 75 08 95 02 09 01 81 02 c0")

FACTORY_DPI = [6, 8, 12, 13, 15, 18]


def default_memory():
    mem = bytearray(0x40)
    mem[0x00:0x08] = bytes.fromhex("5a 03 a5 00 40 14 fa 30")
    mem[0x08:0x10] = bytes([1, 2, 3, 4, 5, 6, 0, 0])
    mem[0x10:0x18] = ins.encode_dpi(bytes.fromhex("09 00 00 00 44 00 00 00"), FACTORY_DPI)
    mem[0x18:0x20] = bytes([0x01, 0x3F, 0, 0, 0, 0, 0, 0])
    return mem


class FakeInstantMouse:
    """Simulates the 07 18 memory protocol of an Instant mouse."""

    def __init__(self, mem=None, failed_commits=0):
        self.mem = bytearray(mem if mem is not None else default_memory())
        self.pending = {}
        self.reply = bytes(8)
        self.sent = []
        self.reloads = 0
        self.failed_commits = failed_commits

    def set_feature(self, data):
        data = bytes(data)
        assert len(data) == 8 and data[0] == 0x07
        self.sent.append(data)
        _, cmd, op, idx, lo, hi, val, _last = data
        if cmd == 0x18:
            addr = lo | (hi << 8)
            if op == 0x05:
                self.reply = bytes([0x07, self.mem[addr + idx], 0, 0, 0, 0, 0, 0])
            elif op == 0x03:
                self.pending[addr + idx] = val
            elif op == 0x09:
                if self.failed_commits:
                    self.failed_commits -= 1
                else:
                    for a, v in self.pending.items():
                        self.mem[a] = v
                self.pending.clear()
            elif op == 0x10:
                self.reloads += 1
        return 8

    def get_feature(self, rid, length):
        return self.reply

    def writes(self):
        return [p for p in self.sent if p[1] == 0x18 and p[2] == 0x03]


def no_sleep(_):
    pass


# ---- encoding vs reference implementation --------------------------------- #


@pytest.mark.parametrize("key", [k for k in VECTORS if k.startswith("mode:")])
def test_mode_packets_match_reference(key):
    _, mode, s, b, d = key.split(":")
    assert mode in ISY_MODE_IDS
    got = ins.mode_packet(ins.MODES[mode], int(s), int(b), int(d)).hex(" ")
    assert got == VECTORS[key]


@pytest.mark.parametrize("key", [k for k in VECTORS if k.startswith("color:")])
def test_color_packets_match_reference(key):
    _, level, color = key.split(":")
    assert ins.color_packet(int(level), color).hex(" ") == VECTORS[key]


def test_full_lighting_sequences_match_reference():
    red = ins.lighting_packets("static", ["#ff0000"], brightness=7)
    assert [p.hex(" ") for p in red] == VECTORS["preset:static-red"]
    assert [p.hex(" ") for p in ins.lighting_packets("off")] == VECTORS["preset:off"]
    rainbow = ins.lighting_packets("rainbow", speed=2, direction=1)
    assert [p.hex(" ") for p in rainbow] == VECTORS["preset:rainbow"]


def test_dpi_codec_matches_reference():
    blk = bytes([0x09, 0x00, 0x00, 0xC5, 0x44, 0x68, 0xCD, 0xF2])
    assert ins.decode_dpi(blk) == VECTORS["dpi:decode"]
    assert ins.encode_dpi(blk, [1, 8, 16, 20, 24, 12]).hex(" ") == VECTORS["dpi:encode"]
    for codes in ([6, 8, 12, 13, 15, 18], [1, 24, 16, 17, 2, 10]):
        assert ins.decode_dpi(ins.encode_dpi(blk, codes)) == codes


def test_input_validation():
    with pytest.raises(ins.InstantError, match="unknown mode"):
        ins.lighting_packets("disco")
    with pytest.raises(ins.InstantError, match="speed"):
        ins.lighting_packets("rainbow", speed=9)
    with pytest.raises(ins.InstantError, match="invalid colour"):
        ins.lighting_packets("static", ["red"])
    with pytest.raises(ins.InstantError, match="invalid DPI code"):
        ins.encode_dpi(bytes(8), [11, 1, 2, 3, 4, 5])
    assert ins.dpi_to_code(800) == 4 and ins.dpi_to_code(4800) == 24  # reference mouse: code x 200
    with pytest.raises(ins.InstantError, match="not a known value"):
        ins.dpi_to_code(2200)
    assert ins.quantize("#123456") == "#113355"


