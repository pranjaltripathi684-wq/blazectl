REAL_BUTTONS = bytes.fromhex("21 22 63 64 a5 b5 00 66")
REAL_DPI = bytes.fromhex("e9 00 00 38 08 de f3 57")


def test_buttons_decode_real_factory_mapping():
    m = ins.decode_buttons(REAL_BUTTONS, REAL_DPI)
    names = {n: ins.FUNCTION_NAMES[c] for n, c in m.items()}
    assert names == {1: "left-click", 2: "right-click", 3: "middle-click", 4: "forward", 5: "back",
                     6: "dpi-loop", 7: "led-loop", 8: "rapid-fire"}


def test_buttons_encoder_reproduces_official_app_bytes():
    # app: button 7 -> Middle Click  => 0x08 byte 5 became a2 (real dump btn7_v2.json)
    b, d = ins.encode_buttons(REAL_BUTTONS, REAL_DPI, {7: ins.BUTTON_FUNCTIONS["middle-click"]})
    assert b.hex(" ") == "21 22 63 64 a5 a2 00 66" and d == REAL_DPI
    # app: button 3 -> DPI Loop  => byte 1 became 26 (real dump btn3.json)
    b, d = ins.encode_buttons(REAL_BUTTONS, REAL_DPI, {3: ins.BUTTON_FUNCTIONS["dpi-loop"]})
    assert b.hex(" ") == "21 26 63 64 a5 b5 00 66"
    # app: button 8 -> DPI Loop => 0x10[0] became e6 (real dump btn8_dpi.json), and it works
    b, d = ins.encode_buttons(REAL_BUTTONS, REAL_DPI, {8: ins.BUTTON_FUNCTIONS["dpi-loop"]})
    assert d[0] == 0xE6 and d[1:] == REAL_DPI[1:] and b == REAL_BUTTONS
    # app: button 8 -> Backward wrote e4 (btn8_back.json) but it does nothing on the mouse
    with pytest.raises(ins.InstantError, match="only supports"):
        ins.encode_buttons(REAL_BUTTONS, REAL_DPI, {8: ins.BUTTON_FUNCTIONS["back"]})
    bad_dpi = bytes([0xE4]) + REAL_DPI[1:]  # what the 8=back test left behind
    b, d = ins.encode_buttons(REAL_BUTTONS, bad_dpi, {8: ins.BUTTON_FUNCTIONS["rapid-fire"]})
    assert d == REAL_DPI


def test_buttons_safety_rules():
    with pytest.raises(ins.InstantError, match="Left Click"):
        ins.encode_buttons(REAL_BUTTONS, REAL_DPI, {1: ins.BUTTON_FUNCTIONS["back"]})
    # moving left click to another button first is fine
    b, _ = ins.encode_buttons(REAL_BUTTONS, REAL_DPI, {1: 0x03, 2: 0x01})
    assert ins.decode_buttons(b, REAL_DPI)[2] == 0x01
    with pytest.raises(ins.InstantError, match="not a known function"):
        ins.encode_buttons(REAL_BUTTONS, REAL_DPI, {7: 0x17})
    with pytest.raises(ins.InstantError, match="buttons are 1-8"):
        ins.encode_buttons(REAL_BUTTONS, REAL_DPI, {9: 0x01})


def test_set_buttons_verified_write_and_refuses_unknown_state():
    fake = FakeInstantMouse()
    fake.mem[0x08:0x10] = REAL_BUTTONS
    fake.mem[0x10:0x18] = REAL_DPI
    m = ins.InstantMouse(fake, sleep=no_sleep)
    res = m.set_buttons({7: 0x02})
    assert res["changed"] and fake.reloads == 1
    assert bytes(fake.mem[0x08:0x10]).hex(" ") == "21 22 63 64 a5 a2 00 66"
    assert bytes(fake.mem[0x10:0x18]) == REAL_DPI
    fake2 = FakeInstantMouse()
    fake2.mem[0x08:0x10] = bytes.fromhex("21 22 63 64 a5 b7 00 66")  # unknown code 0x17
    fake2.mem[0x10:0x18] = REAL_DPI
    with pytest.raises(ins.InstantError, match="doesn't know yet"):
        ins.InstantMouse(fake2, sleep=no_sleep).set_buttons({3: 0x02})
    assert fake2.writes() == []


