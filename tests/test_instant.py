def test_blaze_ultra_table_matches_real_dumps():
    """Real memory from the user's Blaze Ultra, with the DPI the official app showed."""
    original = bytes.fromhex("e9 00 00 30 08 35 c9 28")  # app: 600 1000 2400 1800 7200 12800
    mapping = bytes.fromhex("e9 00 00 30 08 12 48 18")   # app: 200 400 800 1600 6400 12800
    to_dpi = lambda blk: [ins.code_to_dpi(c, 0x1440) for c in ins.decode_dpi(blk)]
    assert to_dpi(original) == [600, 1000, 2400, 1800, 7200, 12800]
    assert to_dpi(mapping) == [200, 400, 800, 1600, 6400, 12800]
    # our encoder reproduces the official app's exact bytes
    codes = [ins.dpi_to_code(d, 0x1440) for d in (200, 400, 800, 1600, 6400, 12800)]
    assert ins.encode_dpi(original, codes) == mapping


def test_blaze_ultra_full_table():
    t = ins.dpi_table(0x1440)
    assert sorted(t) == list(ins.DPI_CODES)  # exactly the 23 codes the chip supports
    values = [t[c] for c in sorted(t)]
    assert values == sorted(values)  # monotonic
    slider = [2400, 3200, 4000, 4800, 5600, 6400, 7200, 8000, 8800, 9600, 10400, 11200, 12800]
    assert [v for v in values if v >= 2400] == slider  # the official app's slider stops
    assert values[:10] == list(range(200, 2001, 200))
    # every value observed in a real memory dump agrees
    observed = {1: 200, 2: 400, 3: 600, 4: 800, 5: 1000, 8: 1600, 9: 1800, 12: 2400, 17: 6400, 18: 7200, 24: 12800}
    assert {c: t[c] for c in observed} == observed
    assert set(observed) == ins.BLAZE_ULTRA_OBSERVED


