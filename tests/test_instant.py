    capsys.readouterr()
    cli.main(["memdiff", str(tmp_path / "a.json"), str(tmp_path / "b.json")])
    out = capsys.readouterr().out
    assert "0x008:" in out and "0x300:" in out and "[33]" in out and "[99]" in out
    assert "2 byte(s) changed in 2 block(s)" in out
    cli.main(["memdiff", str(tmp_path / "a.json"), str(tmp_path / "a.json")])
    assert "No differences" in capsys.readouterr().out
    with pytest.raises(ins.InstantError):
        ins.InstantMouse(fake_cli, sleep=no_sleep).dump(0x10001)
